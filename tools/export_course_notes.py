TYPE_NAMES = {
    "choice": "Question à choix",
    "math": "Calcul mathématique",
    "code": "Lecture de code",
    "reading": "Compréhension écrite",
    "listening": "Compréhension orale",
    "spoken": "Atelier de production orale",
    "written": "Atelier de production écrite",
}


def esc(value) -> str:
    return html.escape(str(value), quote=True)


def paragraph(value: str) -> str:
    return "<p>" + esc(value).replace("\r\n", "\n").replace("\n", "<br>\n") + "</p>"


def learning_notes(value: str) -> str:
    """Keep the explicit teaching Markdown usable on GitHub as well as in the app."""
    lines = []
    fenced = False
    display_math = False
    for line in value.splitlines():
        if line.startswith("```"):
            fenced = not fenced
            lines.append(line)
            continue
        if fenced:
            lines.append(line)
            continue
        if line.strip() == "$$":
            display_math = not display_math
            lines.append(line)
            continue
        if display_math:
            lines.append(line)
            continue
        if line.startswith("## "):
            line = "#" + line  # Course h1, lesson h2, teaching section h3.
        elif line.startswith("### "):
            line = "#" + line
        prefix = "> " if line.startswith("> ") else ""
        prose = line[len(prefix):]
        # Preserve authored code and TeX; escape literal HTML in ordinary copy.
        parts = re.split(r"(`[^`]+`|\$\$.*?\$\$|\$[^$]+\$)", prose)
        lines.append((prefix + "".join(part if part.startswith(("`", "$")) else html.escape(part, quote=False) for part in parts)).rstrip())
    return "\n".join(lines)


def link(url: str, label: str) -> str:
    safe_url = quote(url, safe=":/?#[]@!$&'()*+,;=%")
    return f'<a href="{esc(safe_url)}" rel="noopener">{esc(label)}</a>'


def kind_label(kind: str) -> str:
    return {
        "course_site": "Site du cours", "resource_collection": "Collection de ressources",
        "textbook_pdf": "Manuel complet (PDF)", "textbook_html": "Manuel en ligne",
        "course_notes_pdf": "Notes de cours (couverture partielle)", "pdf": "PDF de séance",
        "course_section": "Section de séance", "video": "Vidéo", "download": "Fichier de cours",
    }.get(kind, kind)


def coverage_label(coverage: str) -> str:
    return {
        "complete_textbook": "manuel complet déclaré par la source",
        "partial_textbook": "document partiel; ne constitue pas un manuel complet",
        "course_materials_index": "index de supports, couverture selon les éléments liés",
        "course_index": "page d’index du cours",
        "session": "support lié à cette séance",
        "complete_html_textbook": "texte complet en ligne annoncé par l’éditeur",
    }.get(coverage, coverage.replace("_", " "))


def load_ordering() -> list[str]:
    text = ORDERING_KT.read_text(encoding="utf-8")
    order_pairs = re.findall(r'^\s*"([a-z][a-z0-9_]+)"\s+to\s+(\d+),\s*$', text, re.MULTILINE)
    if not order_pairs:
        raise ValueError(f"Could not read OSSU course order from {ORDERING_KT.relative_to(ROOT)}")
    ranks = {course_id: int(rank) for course_id, rank in order_pairs}
    declared = [course_id for _, group_ids in OSSU_GROUPS[:-1] for course_id in group_ids]
    if set(ranks) != set(declared):
        raise ValueError(f"OSSU_GROUPS differs from CourseOrdering.kt: source={sorted(ranks)}, groups={sorted(declared)}")
    for group_name, group_ids in OSSU_GROUPS[:-1]:
        if group_ids != sorted(group_ids, key=lambda course_id: ranks[course_id]):
            raise ValueError(f"{group_name} does not follow its CourseOrdering.kt ranks")
    return declared


def load_inputs():
    courses, errors = curriculum_validator.load_authored()
    if errors:
        raise ValueError("Curriculum validation failed: " + "; ".join(errors[:20]))
    if len(courses) != 15:
        raise ValueError(f"Expected 15 published courses; found {len(courses)}")
    resource_data = json.loads(RESOURCE_CATALOG.read_text(encoding="utf-8"))
    resource_errors = resource_validator.validate(resource_data)
    if resource_errors:
        raise ValueError("Resource catalog validation failed: " + "; ".join(resource_errors[:20]))
    load_ordering()
    course_map = {course["courseId"]: course for course, _ in courses}
    resource_courses = {entry["courseId"]: entry for entry in resource_data["courses"]}
    if set(course_map) != set(resource_courses):
        raise ValueError("Published course and resource catalog IDs differ")
    return course_map, resource_courses, resource_data


def render_resource(resource: dict) -> str:
    url = link(resource["url"], resource["title"])
    detail = (
        f"<li>{url} <em>({esc(kind_label(resource['kind']))}; "
        f"{esc(coverage_label(resource['coverage']))}; {esc(resource['language'])})</em>"
    )
    if resource.get("sourceUrl") and resource["sourceUrl"] != resource["url"]:
        detail += f"<br>Page source : {link(resource['sourceUrl'], resource['sourceUrl'])}"
    notes = resource.get("notes")
    if notes:
        detail += "<br>"
        detail += esc(notes)
    return detail + "</li>"


def audio_repo_link(course_id: str, exercise: dict) -> str | None:
    relative = exercise.get("audioResourcePath")
    if not relative:
        return None
    if not re.fullmatch(r"files/audio/[a-z0-9_]+\.wav", relative):
        raise ValueError(f"{exercise.get('id')}: invalid bundled audio path")
    asset = ROOT / "composeApp/src/commonMain/composeResources" / relative
    if not asset.is_file():
        raise ValueError(f"{exercise.get('id')}: audio asset not found: {relative}")
    return "../../composeApp/src/commonMain/composeResources/" + relative


def render_exercise(exercise: dict) -> str:
    exercise_id = exercise["id"]
    exercise_type = TYPE_NAMES.get(exercise["type"], exercise["type"])
    out = [f'<a id="{esc(exercise_id)}"></a>', f"#### {esc(exercise_type)}", paragraph(exercise["prompt"])]
    if exercise.get("passage"):
        out.extend(("**Texte à lire**", paragraph(exercise["passage"])))
    if exercise.get("transcript"):
        out.extend(("**Transcription de l’audio original**", paragraph(exercise["transcript"])))
    repo_audio = audio_repo_link("", exercise)
    if repo_audio:
        out.append(f"Audio original du dépôt : {link(repo_audio, Path(repo_audio).name)}")
    snippet = exercise.get("codeSnippet")
    if snippet:
        out.extend(("**Extrait de code**", "<pre><code>" + esc(snippet) + "</code></pre>"))
    if exercise.get("options"):
        out.append("**Propositions**")
        out.append("<ol>" + "".join(f"<li>{esc(option)}</li>" for option in exercise["options"]) + "</ol>")
        answer = exercise.get("correctOptionIndex")
        if type(answer) is int and 0 <= answer < len(exercise["options"]):
            out.append("**Réponse attendue :** " + esc(exercise["options"][answer]))
    if exercise.get("minWords") is not None:
        out.append(f"**Longueur de pratique :** {exercise['minWords']} à {exercise['maxWords']} mots (consigne de l’atelier).")
    if exercise.get("maxDurationSeconds") is not None:
        out.append(f"**Durée de pratique :** jusqu’à {exercise['maxDurationSeconds']} secondes; préparation indiquée : {exercise['preparationSeconds']} secondes.")
    for field, heading in (("exampleOutline", "Trame proposée"), ("exampleResponse", "Exemple original")):
        if exercise.get(field):
            out.extend((f"**{heading}**", paragraph(exercise[field])))
    if exercise.get("roleplayTurns"):
        out.append("**Répliques de pratique**")
        out.append("<ol>" + "".join(f"<li>{esc(turn)}</li>" for turn in exercise["roleplayTurns"]) + "</ol>")
    if exercise.get("reviewCriteria"):
        out.append("**Grille d’autoévaluation**")
        out.append("<ul>" + "".join(f"<li>{esc(item)}</li>" for item in exercise["reviewCriteria"]) + "</ul>")
        out.append("Cette grille sert à la pratique; elle ne calcule ni ne prédit un score officiel.")
    if exercise.get("hint"):
        out.extend(("**Indice**", paragraph(exercise["hint"])))
    if exercise.get("explanation"):
        out.extend(("**Correction / retour**", paragraph(exercise["explanation"])))
    if exercise.get("verification"):
        out.extend(("**Vérification**", paragraph(exercise["verification"])))
    return "\n\n".join(out)


def render_course(course: dict, resource_course: dict, sessions_by_key: dict) -> str:
    cid = course["courseId"]
    out = [MARKER, f"# {esc(course['title'])}", "", f"**Cours source :** {esc(course['sourceTitle'])}<br>",
           f"**Édition :** {esc(course['edition'])}<br>", f"**Séances :** {len(course['lessons'])}", "",
           paragraph(course.get("description", "Cours adapté en français à partir de ressources externes.")), "",
           "## Sommaire", ""]
    out.extend(f"- [Séance {lesson['sourceSessionNumber']} — {esc(lesson['title'])}](#{lesson['id']})" for lesson in course["lessons"])
    out.extend(("", "## Ressources du cours", "",
                f"Statuts de licence, précautions de réutilisation et provenance détaillée : [consulter la notice](../curriculum/course-resources-notes.md).", "", "<ul>"))
    out.extend(render_resource(r) for r in resource_course["resources"])
    out.extend(("</ul>", "", "> Ces notes pédagogiques originales en français accompagnent les séances et exercices du dépôt. Elles ne sont pas une traduction intégrale d’un manuel source; les ressources originales restent accessibles via leurs liens.", ""))
    for lesson in course["lessons"]:
        session_key = (cid, lesson["sourceSessionNumber"])
        resource_session = sessions_by_key.get(session_key, {})
        out.extend((f'<a id="{esc(lesson["id"])}"></a>',
                    f"## Séance {lesson['sourceSessionNumber']} — {esc(lesson['title'])}", "",
                    f"**Séance source :** {esc(lesson['sourceTitle'])}<br>",
                    f"**Objectif :** {esc(lesson['objective'])}", "",
                    learning_notes(lesson["learningNotes"]), "", "### Références de cette séance", "", "<ul>"))
        for resource in resource_session.get("resources", []):
            out.append(render_resource(resource))
        if not resource_session.get("resources"):
            for source_url in lesson.get("sourceUrls", []):
                out.append(f"<li>{link(source_url, source_url)}</li>")
        out.extend(("</ul>", "", "### Exercices", ""))
        for exercise in lesson["exercises"]:
            out.extend((f'<details id="exercise-details-{esc(exercise["id"])}">',
                        f"<summary>{esc(exercise['id'])} — {esc(TYPE_NAMES.get(exercise['type'], exercise['type']))}</summary>", "",
                        render_exercise(exercise), "", "</details>", ""))
    return "\n".join(out).rstrip() + "\n"


def render_index(course_map: dict) -> str:
    out = [MARKER, "# Notes de cours et exercices originaux", "",
           "Cette bibliothèque regroupe les notes françaises originales et les exercices rédigés du dépôt. Les références externes sont appariées aux séances; les supports source restent liés sur leurs sites officiels. Les notes ne prétendent pas traduire intégralement les manuels MIT ou les autres ouvrages.", "",
           "Les ressources PDF sont des liens externes. Leur couverture et leur statut de licence sont indiqués dans la page du cours; aucun document source n’est copié ici.", ""]
    for group_title, course_ids in OSSU_GROUPS:
        out.extend((f"## {group_title}", ""))
        for cid in course_ids:
            course = course_map[cid]
            out.append(f"- [{esc(course['title'])}]({cid}.md) — {len(course['lessons'])} séances")
        out.append("")
    out.extend(("## Parcours pédagogique", "",
                "L’ordre OSSU suit les rangs déclarés dans `CourseOrdering.kt`: mathématiques fondamentales puis sujets avancés; informatique fondamentale, programmation avancée et théorie avancée. Les quatre ateliers TCF sont regroupés à part, dans l’ordre compréhension orale, compréhension écrite, production orale, production écrite. Ces ateliers sont originaux et ne produisent pas de score officiel.", ""))
    return "\n".join(out)


def render_all():
    course_map, resource_course_map, resource_data = load_inputs()
    sessions_by_key = {(s["courseId"], s["sessionNumber"]): s for s in resource_data["sessions"]}
    rendered = {OUTPUT_DIR / f"{cid}.md": render_course(course_map[cid], resource_course_map[cid], sessions_by_key)
                for _, ids in OSSU_GROUPS for cid in ids}
    if set(rendered) != {OUTPUT_DIR / f"{cid}.md" for cid in course_map}:
        raise ValueError("Export ordering does not cover exactly the published courses")
    rendered[INDEX] = render_index(course_map)
    return rendered


def run(write: bool) -> int:
    outputs = render_all()
    mismatches = []
    for path, expected in outputs.items():
        if path.exists():
            existing = path.read_text(encoding="utf-8")
            if not existing.startswith(MARKER):
                raise ValueError(f"Refusing to overwrite unowned file: {path.relative_to(ROOT)}")
            if existing != expected:
                mismatches.append(path)
        else:
            mismatches.append(path)
    if not write:
        if mismatches:
            print("Stale or missing exports:")
            for path in mismatches:
                print(f"  {path.relative_to(ROOT)}")
            return 1
        print(f"PASS: {len(outputs)-1} course notes and index match validated JSON.")
        return 0
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
    total_bytes = sum(path.stat().st_size for path in outputs)
    print(f"Wrote {len(outputs)-1} course notes and index ({total_bytes} bytes total).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="validate sources and check that exports are current")
    mode.add_argument("--write", action="store_true", help="write/update only this generator's marked outputs")
    args = parser.parse_args()
    try:
        return run(args.write)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
